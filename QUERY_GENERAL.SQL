WITH SLA AS (
  -- DISTINCT es más claro y eficiente que GROUP BY ALL sobre todas las columnas
  SELECT DISTINCT
    CAST(INBOUND_ID AS INT64) AS INBOUND_ID_INT,
    INBOUND_ID                AS INBOUND_ID_STR,
    DATA_SLA,
    HOUR_SLA,
    SLA_DATE_ADJUSTED,
    PROCESS_FINISH_DATE
  FROM `meli-bi-data.WHOWNER.DM_INBOUND_SLA_PROCESS_HOUR`
),

UDS_PUT AS (
  SELECT
 FBM_REASON_ID AS IS_PUT,
 SUM(FBM_QUANTITY) AS PUT_FBM_QUANTITY
    FROM `meli-bi-data.WHOWNER.BT_FBM_STOCK_3_MOVEMENT`
    WHERE
      WAREHOUSE_ID IN ('COCU02')
      AND FBM_REASON_PROCESS = 'put_away'
      GROUP BY 1
      ORDER BY 1
),

UDS_CHK AS (
  SELECT
 FBM_REASON_ID AS IS_CHK,
 SUM(FBM_QUANTITY) AS CHCK_FBM_QUANTITY
    FROM `meli-bi-data.WHOWNER.BT_FBM_STOCK_3_MOVEMENT`
    WHERE
      WAREHOUSE_ID IN ('COCU02')
      AND FBM_CREATED_DATE >= "2026-05-01"
      --AND FBM_REASON_PROCESS = 'put_away'
      AND FBM_REASON_PROCESS = 'inbound'
      --AND FBM_EVENT_TYPE = "InputPerformed"
      GROUP BY 1
),

BOXES AS (
  SELECT
    RESOURCE_ID,
    CAST(RESOURCE_ID AS INT64)              AS RESOURCE_ID_INT,
    COUNT(DISTINCT SHIPMENT_VOLUME_ID)      AS N_BOX_ID
  FROM `meli-bi-data.WHOWNER.BT_FBM_WMS_INBOUND_OPS_EVENT_RECEIVING_SHIPMENT`
  GROUP BY RESOURCE_ID
),

REOPENED AS (
  SELECT DISTINCT
    INBOUND_ID,
    CAST(INBOUND_ID AS INT64) AS INBOUND_ID_INT
  FROM `meli-bi-data.WHOWNER.BT_SHP_MT_INBOUND_REOPENING`
)

SELECT
  AGG.WAREHOUSE_ID,
  AGG.IB_ID,
  AGG.IS_TYPE,
  EXTRACT(DATE FROM AGG.INB_ARRIVAL_DATETIME)                               AS ARRIVAL_DATE,
  SLA.DATA_SLA                                                              AS SLA_DATE,
  SLA.HOUR_SLA,
  SLA.SLA_DATE_ADJUSTED                                                     AS SLA_DATETIME,
  SLA.PROCESS_FINISH_DATE                                                   AS PROCESS_FINISH_DATETIME,
  AGG.INB_ARRIVAL_DATETIME,
  AGG.INB_RECEPTION_DATETIME,
  AGG.CHECKIN_FIRSTMOV,
  AGG.CHECKIN_LASTMOV,
  AGG.PUTAWAY_FIRSTMOV,
  AGG.PUTAWAY_LASTMOV,
  AGG.UNITS_RECEIVED                                                        AS RECEIVING,
  BOXES.N_BOX_ID,
  UC.CHCK_FBM_QUANTITY,
  UP.PUT_FBM_QUANTITY,
  
  -- ⏱️ ARRIVE → RECEIVING
  DATETIME_DIFF(AGG.INB_RECEPTION_DATETIME, AGG.INB_ARRIVAL_DATETIME, HOUR) AS HOUR_ARRIVE_TO_RECEIVING,

  -- ⏱️ RECEIVING → CHECKIN (primer mov)
  DATETIME_DIFF(AGG.CHECKIN_FIRSTMOV, AGG.INB_RECEPTION_DATETIME, HOUR)    AS HOUR_RECEIVING_TO_CHECKIN_START,

  -- ⏱️ CHECKIN (duración)
  DATETIME_DIFF(AGG.CHECKIN_LASTMOV, AGG.CHECKIN_FIRSTMOV, HOUR)           AS HOUR_CHECKIN_DURATION,

  -- ⏱️ CHECKIN → PUTAWAY
  DATETIME_DIFF(AGG.PUTAWAY_FIRSTMOV, AGG.CHECKIN_LASTMOV, HOUR)           AS HOUR_CHECKIN_TO_PUTAWAY_START,

  -- ⏱️ PUTAWAY (duración)
  DATETIME_DIFF(AGG.PUTAWAY_LASTMOV, AGG.PUTAWAY_FIRSTMOV, HOUR)           AS HOUR_PUTAWAY_DURATION,

  -- ⏱️ TOTAL
  DATETIME_DIFF(AGG.PUTAWAY_LASTMOV, AGG.INB_ARRIVAL_DATETIME, HOUR)       AS HOUR_TOTAL_PROCESS,

  CASE WHEN AGG.PUTAWAY_LASTMOV IS NULL THEN 'open' ELSE 'closed' END      AS SLA_MISSED,
  CASE WHEN RP.INBOUND_ID_INT = AGG.IB_ID THEN 'reopened' ELSE 'not_reopened' END AS REOPENED

FROM `meli-bi-data.WHOWNER.DM_OPS_IB_DETAILS_AGG` AGG

LEFT JOIN SLA
  ON AGG.IB_ID = SLA.INBOUND_ID_INT

LEFT JOIN BOXES
  ON AGG.IB_ID = BOXES.RESOURCE_ID_INT

LEFT JOIN REOPENED RP
  ON AGG.IB_ID = RP.INBOUND_ID_INT

LEFT JOIN UDS_PUT UP
  ON AGG.IB_ID = CAST(UP.IS_PUT AS INT64)

LEFT JOIN UDS_CHK UC
  ON AGG.IB_ID = CAST(UC.IS_CHK AS INT64)

WHERE
  AGG.WAREHOUSE_ID = 'COCU02'
  -- Filtro directo sobre la columna para habilitar partition pruning
  AND AGG.INB_ARRIVAL_DATETIME >= '2026-01-01'
  AND AGG.INB_ARRIVAL_DATETIME  < '2027-01-01'

ORDER BY AGG.IB_ID