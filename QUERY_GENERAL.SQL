-- ============================================================================
-- QUERY MASTER — con rangos de comparación para columnas SLA_VS_*
-- Se envuelve el SELECT principal en un CTE (BASE) para poder referenciar
-- los alias SLA_VS_* en los CASE de rango (no se puede dentro del mismo SELECT).
-- Buckets: <=5, <=10, <=20, <=30, <=40, <=48, >48 (límites INCLUSIVOS arriba).
-- A0 captura los inbounds abiertos (SLA_VS_* = NULL) para que NO caigan en >48.
-- ============================================================================

WITH
SLA AS (
  SELECT DISTINCT
    CAST(INBOUND_ID AS INT64) AS INBOUND_ID_INT,
    DATA_SLA,
    HOUR_SLA,
    SLA_DATE_ADJUSTED,
    PROCESS_FINISH_DATE
  FROM `meli-bi-data.WHOWNER.DM_INBOUND_SLA_PROCESS_HOUR`
  WHERE DATA_SLA >= DATE '2026-01-01'        -- VERIFICAR que DATA_SLA sea la columna de partición
    AND DATA_SLA <  DATE '2027-01-05'        -- margen extra: el SLA puede caer unos días después del arribo
    -- AND WAREHOUSE_ID = 'COCU02'           -- AGREGAR si la tabla tiene la columna (ayuda si está clustered)
),

UDS AS (
  SELECT
    CAST(FBM_REASON_ID AS INT64) AS REASON_INT,
    SUM(IF(FBM_REASON_PROCESS = 'put_away', FBM_QUANTITY, 0)) AS PUT_FBM_QUANTITY,
    SUM(IF(FBM_REASON_PROCESS = 'inbound',  FBM_QUANTITY, 0)) AS CHCK_FBM_QUANTITY
  FROM `meli-bi-data.WHOWNER.BT_FBM_STOCK_3_MOVEMENT`
  WHERE WAREHOUSE_ID = 'COCU02'
    AND FBM_REASON_PROCESS IN ('put_away', 'inbound')
    AND FBM_CREATED_DATE >= DATE '2026-01-01'   -- VERIFICAR columna de partición (FBM_CREATED_DATE?)
  GROUP BY REASON_INT
),

BOXES AS (
  SELECT
    CAST(RESOURCE_ID AS INT64)         AS RESOURCE_ID_INT,
    COUNT(DISTINCT SHIPMENT_VOLUME_ID) AS N_BOX_ID,
  FROM `meli-bi-data.WHOWNER.BT_FBM_WMS_INBOUND_OPS_EVENT_RECEIVING_SHIPMENT`
  WHERE WAREHOUSE_ID = 'COCU02'                 -- VERIFICAR que exista la columna
    -- AND <FECHA_EVENTO> >= DATE '2026-01-01'  -- AGREGAR filtro de fecha/partición si hay columna
  GROUP BY RESOURCE_ID_INT
),

REOPENED AS (
  SELECT DISTINCT
    CAST(INBOUND_ID AS INT64) AS INBOUND_ID_INT
  FROM `meli-bi-data.WHOWNER.BT_SHP_MT_INBOUND_REOPENING`
  -- WHERE <FECHA> >= DATE '2026-01-01'         -- AGREGAR si hay columna de fecha/partición
),

-- ── BASE: tu SELECT principal, ahora como CTE ────────────────────────────────
BASE AS (
  SELECT
    AGG.WAREHOUSE_ID,
    AGG.IB_ID,
    AGG.IS_TYPE,
    EXTRACT(DATE FROM AGG.INB_ARRIVAL_DATETIME)                               AS ARRIVAL_DATE,
    SLA.DATA_SLA                                                              AS SLA_DATE,
    SLA.HOUR_SLA,
    SLA.SLA_DATE_ADJUSTED                                                     AS SLA_DATETIME,
    SLA.PROCESS_FINISH_DATE - INTERVAL 1 HOUR                                 AS SLA_FINISH_DATETIME,
    AGG.INB_ARRIVAL_DATETIME,
    AGG.INB_RECEPTION_DATETIME,
    AGG.CHECKIN_FIRSTMOV,
    AGG.CHECKIN_LASTMOV,
    AGG.PUTAWAY_FIRSTMOV,
    AGG.PUTAWAY_LASTMOV,
    AGG.UNITS_RECEIVED                                                        AS RECEIVING,
    BOXES.N_BOX_ID,
    UC.CHCK_FBM_QUANTITY,
    UP.PUT_FBM_QUANTITY,

    DATETIME_DIFF(AGG.INB_RECEPTION_DATETIME, AGG.INB_ARRIVAL_DATETIME, HOUR) AS HOUR_ARRIVE_TO_RECEIVING,
    DATETIME_DIFF(AGG.CHECKIN_FIRSTMOV, AGG.INB_RECEPTION_DATETIME, HOUR)     AS HOUR_RECEIVING_TO_CHECKIN_START,
    DATETIME_DIFF(AGG.CHECKIN_LASTMOV, AGG.CHECKIN_FIRSTMOV, HOUR)            AS HOUR_CHECKIN_DURATION,
    DATETIME_DIFF(AGG.PUTAWAY_FIRSTMOV, AGG.CHECKIN_LASTMOV, HOUR)            AS HOUR_CHECKIN_TO_PUTAWAY_START,
    DATETIME_DIFF(AGG.PUTAWAY_LASTMOV, AGG.PUTAWAY_FIRSTMOV, HOUR)            AS HOUR_PUTAWAY_DURATION,
    DATETIME_DIFF(AGG.PUTAWAY_LASTMOV, AGG.INB_ARRIVAL_DATETIME, HOUR)        AS HOUR_TOTAL_PROCESS,

    CASE WHEN SLA.PROCESS_FINISH_DATE IS NULL THEN 'open' ELSE 'closed' END          AS SLA_STATUS,
    CASE WHEN RP.INBOUND_ID_INT = AGG.IB_ID THEN 'reopened' ELSE 'not_reopened' END  AS REOPENED,

    -- RANGOS (diferencias)
    DATETIME_DIFF(SLA.SLA_DATE_ADJUSTED, AGG.INB_ARRIVAL_DATETIME, HOUR) AS SLA_VS_ARRIVE,
    DATETIME_DIFF(SLA.SLA_DATE_ADJUSTED, AGG.CHECKIN_FIRSTMOV, HOUR)     AS SLA_VS_CHECKIN_START,
    DATETIME_DIFF(SLA.SLA_DATE_ADJUSTED, AGG.CHECKIN_LASTMOV, HOUR)      AS SLA_VS_CHECKIN_LAST,
    DATETIME_DIFF(SLA.SLA_DATE_ADJUSTED, AGG.PUTAWAY_FIRSTMOV, HOUR)     AS SLA_VS_PUTAWAY_START,
    DATETIME_DIFF(SLA.SLA_DATE_ADJUSTED, AGG.PUTAWAY_LASTMOV, HOUR)      AS SLA_VS_PUTAWAY_LAST

  FROM `meli-bi-data.WHOWNER.DM_OPS_IB_DETAILS_AGG` AGG
  LEFT JOIN SLA      ON AGG.IB_ID = SLA.INBOUND_ID_INT
  LEFT JOIN BOXES    ON AGG.IB_ID = BOXES.RESOURCE_ID_INT
  LEFT JOIN REOPENED RP ON AGG.IB_ID = RP.INBOUND_ID_INT
  LEFT JOIN UDS      UP ON AGG.IB_ID = UP.REASON_INT     -- pendiente: colapsar UP/UC en un solo join (mismo CTE)
  LEFT JOIN UDS      UC ON AGG.IB_ID = UC.REASON_INT     -- y semántica reason_id vs inbound_id
  WHERE
    AGG.WAREHOUSE_ID = 'COCU02'
    AND AGG.INB_ARRIVAL_DATETIME >= DATETIME '2026-01-01'
    AND AGG.INB_ARRIVAL_DATETIME <  DATETIME '2027-01-01'
)

-- ── SELECT FINAL: BASE + columnas de rango ───────────────────────────────────
SELECT
  B.*,

  CASE
    WHEN B.SLA_VS_ARRIVE IS NULL THEN 'A0.(Sin cierre)'
    WHEN B.SLA_VS_ARRIVE <= 5  THEN 'A1.(5 Horas)'
    WHEN B.SLA_VS_ARRIVE <= 10 THEN 'A2.(10 Horas)'
    WHEN B.SLA_VS_ARRIVE <= 20 THEN 'A3.(20 Horas)'
    WHEN B.SLA_VS_ARRIVE <= 30 THEN 'A4.(30 Horas)'
    WHEN B.SLA_VS_ARRIVE <= 40 THEN 'A5.(40 Horas)'
    WHEN B.SLA_VS_ARRIVE <= 48 THEN 'A6.(48 Horas)'
    ELSE 'A7.(>48 Horas)'
  END AS RANGO_SLA_VS_ARRIVE,

  CASE
    WHEN B.SLA_VS_CHECKIN_START IS NULL THEN 'A0.(Sin cierre)'
    WHEN B.SLA_VS_CHECKIN_START <= 5  THEN 'A1.(5 Horas)'
    WHEN B.SLA_VS_CHECKIN_START <= 10 THEN 'A2.(10 Horas)'
    WHEN B.SLA_VS_CHECKIN_START <= 20 THEN 'A3.(20 Horas)'
    WHEN B.SLA_VS_CHECKIN_START <= 30 THEN 'A4.(30 Horas)'
    WHEN B.SLA_VS_CHECKIN_START <= 40 THEN 'A5.(40 Horas)'
    WHEN B.SLA_VS_CHECKIN_START <= 48 THEN 'A6.(48 Horas)'
    ELSE 'A7.(>48 Horas)'
  END AS RANGO_SLA_VS_CHECKIN_START,

  CASE
    WHEN B.SLA_VS_CHECKIN_LAST IS NULL THEN 'A0.(Sin cierre)'
    WHEN B.SLA_VS_CHECKIN_LAST <= 5  THEN 'A1.(5 Horas)'
    WHEN B.SLA_VS_CHECKIN_LAST <= 10 THEN 'A2.(10 Horas)'
    WHEN B.SLA_VS_CHECKIN_LAST <= 20 THEN 'A3.(20 Horas)'
    WHEN B.SLA_VS_CHECKIN_LAST <= 30 THEN 'A4.(30 Horas)'
    WHEN B.SLA_VS_CHECKIN_LAST <= 40 THEN 'A5.(40 Horas)'
    WHEN B.SLA_VS_CHECKIN_LAST <= 48 THEN 'A6.(48 Horas)'
    ELSE 'A7.(>48 Horas)'
  END AS RANGO_SLA_VS_CHECKIN_LAST,

  CASE
    WHEN B.SLA_VS_PUTAWAY_START IS NULL THEN 'A0.(Sin cierre)'
    WHEN B.SLA_VS_PUTAWAY_START <= 5  THEN 'A1.(5 Horas)'
    WHEN B.SLA_VS_PUTAWAY_START <= 10 THEN 'A2.(10 Horas)'
    WHEN B.SLA_VS_PUTAWAY_START <= 20 THEN 'A3.(20 Horas)'
    WHEN B.SLA_VS_PUTAWAY_START <= 30 THEN 'A4.(30 Horas)'
    WHEN B.SLA_VS_PUTAWAY_START <= 40 THEN 'A5.(40 Horas)'
    WHEN B.SLA_VS_PUTAWAY_START <= 48 THEN 'A6.(48 Horas)'
    ELSE 'A7.(>48 Horas)'
  END AS RANGO_SLA_VS_PUTAWAY_START,

  CASE
    WHEN B.SLA_VS_PUTAWAY_LAST IS NULL THEN 'A0.(Sin cierre)'
    WHEN B.SLA_VS_PUTAWAY_LAST <= 5  THEN 'A1.(5 Horas)'
    WHEN B.SLA_VS_PUTAWAY_LAST <= 10 THEN 'A2.(10 Horas)'
    WHEN B.SLA_VS_PUTAWAY_LAST <= 20 THEN 'A3.(20 Horas)'
    WHEN B.SLA_VS_PUTAWAY_LAST <= 30 THEN 'A4.(30 Horas)'
    WHEN B.SLA_VS_PUTAWAY_LAST <= 40 THEN 'A5.(40 Horas)'
    WHEN B.SLA_VS_PUTAWAY_LAST <= 48 THEN 'A6.(48 Horas)'
    ELSE 'A7.(>48 Horas)'
  END AS RANGO_SLA_VS_PUTAWAY_LAST

FROM BASE B
