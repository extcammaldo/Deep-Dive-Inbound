SELECT
  AGG.WAREHOUSE_ID,
  IB_ID,
  IS_TYPE,
  EXTRACT(DATE FROM INB_ARRIVAL_DATETIME) AS ARRIVAL_DATE,
  DATA_SLA AS SLA_DATE,
  HOUR_SLA,
  SLA_DATE_ADJUSTED AS SLA_DATETIME,
  INB_ARRIVAL_DATETIME,
  INB_RECEPTION_DATETIME,
  CHECKIN_FIRSTMOV,
  CHECKIN_LASTMOV,
  PUTAWAY_FIRSTMOV,
  PUTAWAY_LASTMOV,
  AGG.UNITS_RECEIVED AS RECEIVING,
  N_BOX_ID,

  -- ⏱️ ARRIVE → RECEIVING
  DATETIME_DIFF(INB_RECEPTION_DATETIME, INB_ARRIVAL_DATETIME, HOUR)        AS HOUR_ARRIVE_TO_RECEIVING,

  -- ⏱️ RECEIVING → CHECKIN (primer mov)
  DATETIME_DIFF(CHECKIN_FIRSTMOV, INB_RECEPTION_DATETIME, HOUR)            AS HOUR_RECEIVING_TO_CHECKIN_START,

  -- ⏱️ CHECKIN (duración: primer → último mov)
  DATETIME_DIFF(CHECKIN_LASTMOV, CHECKIN_FIRSTMOV, HOUR)                   AS HOUR_CHECKIN_DURATION,

  -- ⏱️ CHECKIN → PUTAWAY (último checkin → primer putaway)
  DATETIME_DIFF(PUTAWAY_FIRSTMOV, CHECKIN_LASTMOV, HOUR)                   AS HOUR_CHECKIN_TO_PUTAWAY_START,

  -- ⏱️ PUTAWAY (duración: primer → último mov)
  DATETIME_DIFF(PUTAWAY_LASTMOV, PUTAWAY_FIRSTMOV, HOUR)                   AS HOUR_PUTAWAY_DURATION,

  -- ⏱️ TOTAL: ARRIVE → PUTAWAY completo
  DATETIME_DIFF(PUTAWAY_LASTMOV, INB_ARRIVAL_DATETIME, HOUR)               AS HOUR_TOTAL_PROCESS,

  CASE WHEN PUTAWAY_LASTMOV IS NULL THEN "open" ELSE "closed" END AS SLA_MISSED,
  CASE WHEN CAST(RP.INBOUND_ID AS INT64) = AGG.IB_ID THEN "reopened" ELSE "not_reopened" END AS REOPENED,

FROM meli-bi-data.WHOWNER.DM_OPS_IB_DETAILS_AGG AGG
LEFT JOIN (
  SELECT
  INBOUND_ID,  
  DATA_SLA,
  HOUR_SLA,
  SLA_DATE_ADJUSTED
  FROM `meli-bi-data.WHOWNER.DM_INBOUND_SLA_PROCESS_HOUR` 
  GROUP BY ALL
) SLA 
  ON AGG.IB_ID = CAST(SLA.INBOUND_ID AS INT64)
LEFT JOIN (
  SELECT
    RESOURCE_ID,
    COUNT(DISTINCT SHIPMENT_VOLUME_ID) AS N_BOX_ID
  FROM meli-bi-data.WHOWNER.BT_FBM_WMS_INBOUND_OPS_EVENT_RECEIVING_SHIPMENT
  GROUP BY ALL
) B_ID
  ON CAST(B_ID.RESOURCE_ID AS INT64) = AGG.IB_ID
  AND SLA.INBOUND_ID = B_ID.RESOURCE_ID
LEFT JOIN  `meli-bi-data.WHOWNER.BT_SHP_MT_INBOUND_REOPENING`  RP ON B_ID.RESOURCE_ID = RP.INBOUND_ID  AND CAST(RP.INBOUND_ID AS INT64) = AGG.IB_ID

WHERE AGG.WAREHOUSE_ID = "COCU02"
  AND EXTRACT(YEAR FROM INB_ARRIVAL_DATETIME) = 2026
  --AND IB_ID = 65938754
ORDER BY 2
;
